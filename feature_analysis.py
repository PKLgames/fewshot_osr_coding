def analyze_correlation(all_features, all_labels):
    """Analyze correlation between feature dimensions."""
    print("\n" + "=" * 70)
    print("Analysis 5: Inter-Feature Correlation Analysis")
    print("=" * 70)

    fig, axes = plt.subplots(1, 3, figsize=(22, 6))

    for ax_idx, (key, name) in enumerate([
        ('yamnet_128', 'yamnet 128-d'),
        ('fc2_64', 'FC2 64-d'),
        ('final_32', 'Final 32-d')
    ]):
        data = all_features[key]
        corr = np.corrcoef(data.T)

        if corr.shape[0] > 64:
            # For yamnet, show a smaller block for readability
            ax = axes[ax_idx]
            im = ax.imshow(corr, cmap='RdBu_r', vmin=-1, vmax=1, aspect='auto')
            ax.set_title(f'{name} Correlation', fontsize=11, fontweight='bold')
        else:
            ax = axes[ax_idx]
            im = ax.imshow(corr, cmap='RdBu_r', vmin=-1, vmax=1, aspect='auto')
            ax.set_title(f'{name} Correlation', fontsize=11, fontweight='bold')

            # Annotate for small matrices
            if corr.shape[0] <= 32:
                for i in range(corr.shape[0]):
                    for j in range(corr.shape[1]):
                        text_color = 'white' if abs(corr[i, j]) > 0.5 else 'black'
                        ax.text(j, i, f'{corr[i,j]:.2f}', ha='center', va='center',
                                fontsize=5, color=text_color)

        ax.set_xlabel('Dimension')
        ax.set_ylabel('Dimension')
        plt.colorbar(im, ax=ax, shrink=0.8)

        # Statistics
        n_dims = corr.shape[0]
        upper_tri = corr[np.triu_indices(n_dims, k=1)]
        print(f"\n  {name}:")
        print(f"    Mean |corr|: {np.mean(np.abs(upper_tri)):.4f}")
        print(f"    Max corr:    {np.max(upper_tri):.4f}")
        print(f"    Min corr:    {np.min(upper_tri):.4f}")
        high_corr = np.sum(np.abs(upper_tri) > 0.8)
        print(f"    Pairs with |corr|>0.8: {high_corr}/{len(upper_tri)}")

    plt.suptitle('Inter-Dimension Correlation Matrices', fontsize=14, fontweight='bold')
    plt.tight_layout()
    plt.savefig(f'{OUTPUT_DIR}/05_correlation_matrices.png', facecolor='white')
    plt.close()
    print(f"\n  [OK] Saved: {OUTPUT_DIR}/05_correlation_matrices.png")


