# Analysis 8: Known vs Unknown Separability
# ============================================================
def analyze_known_vs_unknown(all_features, all_labels):
    """Analyze how well features separate known from unknown classes."""
    print("\n" + "=" * 70)
    print("Analysis 8: Known vs Unknown Separability Analysis")
    print("=" * 70)

    known_mask = all_labels < NUM_KNOWN
    unknown_mask = all_labels >= NUM_KNOWN

    fig, axes = plt.subplots(1, 3, figsize=(20, 6))

    for ax_idx, (key, name) in enumerate([
        ('yamnet_128', 'yamnet 128-d'),
        ('fc2_64', 'FC2 64-d'),
        ('final_32', 'Final 32-d')
    ]):
        data = all_features[key]

        # L2 norm distribution
        known_norms = np.sqrt(np.sum(data[known_mask] ** 2, axis=1))
        unknown_norms = np.sqrt(np.sum(data[unknown_mask] ** 2, axis=1))

        ax = axes[ax_idx]
        ax.hist(known_norms, bins=80, density=True, alpha=0.5, color='coral',
                label=f'Known (n={known_mask.sum()})')
        ax.hist(unknown_norms, bins=80, density=True, alpha=0.5, color='steelblue',
                label=f'Unknown (n={unknown_mask.sum()})')
        ax.set_title(f'{name} - L2 Norm Distribution', fontsize=11, fontweight='bold')
        ax.set_xlabel('L2 Norm')
        ax.set_ylabel('Density')
        ax.legend(fontsize=8)
        ax.grid(alpha=0.3)

        print(f"\n  {name}:")
        print(f"    Known L2 norm:   {known_norms.mean():.4f} ± {known_norms.std():.4f}")
        print(f"    Unknown L2 norm: {unknown_norms.mean():.4f} ± {unknown_norms.std():.4f}")

        # Per-dimension separability (Cohen's d)
        known_data = data[known_mask]
        unknown_data = data[unknown_mask]
        n_dims = data.shape[1]
        cohens_d = np.zeros(n_dims)
        for d in range(n_dims):
            k = known_data[:, d]
            u = unknown_data[:, d]
            pooled_std = np.sqrt((np.var(k) + np.var(u)) / 2)
            cohens_d[d] = (u.mean() - k.mean()) / pooled_std if pooled_std > 0 else 0

        top_separable = np.argsort(np.abs(cohens_d))[::-1][:5]
        print(f"    Top-5 separable dims (Cohen's d):")
        for dim in top_separable:
            print(f"      Dim {dim}: d={cohens_d[dim]:.4f} "
                  f"(K={known_data[:,dim].mean():.4f}, U={unknown_data[:,dim].mean():.4f})")

    plt.suptitle('Known vs Unknown Separability Analysis', fontsize=14, fontweight='bold')
    plt.tight_layout()
    plt.savefig(f'{OUTPUT_DIR}/08_known_vs_unknown.png', facecolor='white')
    plt.close()
    print(f"\n  [OK] Saved: {OUTPUT_DIR}/08_known_vs_unknown.png")

    # Additional: per-dimension Cohen's d bar chart for final 32-d
    data = all_features['final_32']
    known_data = data[known_mask]
    unknown_data = data[unknown_mask]
    cohens_d = np.zeros(32)
    for d in range(32):
        k = known_data[:, d]
        u = unknown_data[:, d]
        pooled_std = np.sqrt((np.var(k) + np.var(u)) / 2)
        cohens_d[d] = (u.mean() - k.mean()) / pooled_std if pooled_std > 0 else 0

    fig, ax = plt.subplots(figsize=(14, 5))
    colors = ['coral' if d > 0 else 'steelblue' for d in cohens_d]
    bars = ax.bar(range(32), cohens_d, color=colors, alpha=0.7, edgecolor='none')
    ax.axhline(y=0, color='black', linewidth=0.5)
    ax.axhline(y=0.2, color='green', linestyle='--', alpha=0.5, label='Small effect (0.2)')
    ax.axhline(y=0.5, color='orange', linestyle='--', alpha=0.5, label='Medium effect (0.5)')
    ax.axhline(y=0.8, color='red', linestyle='--', alpha=0.5, label='Large effect (0.8)')
    ax.axhline(y=-0.2, color='green', linestyle='--', alpha=0.5)
    ax.axhline(y=-0.5, color='orange', linestyle='--', alpha=0.5)
    ax.axhline(y=-0.8, color='red', linestyle='--', alpha=0.5)
    ax.set_xlabel('Dimension')
    ax.set_ylabel("Cohen's d (Unknown - Known)")
    ax.set_title("Final 32-d: Per-Dimension Known vs Unknown Effect Size (Cohen's d)",
                 fontsize=12, fontweight='bold')
    ax.legend(fontsize=8)
    ax.grid(alpha=0.3, axis='y')
    plt.tight_layout()
    plt.savefig(f'{OUTPUT_DIR}/08_cohens_d.png', facecolor='white')
    plt.close()
    print(f"  [OK] Saved: {OUTPUT_DIR}/08_cohens_d.png")


