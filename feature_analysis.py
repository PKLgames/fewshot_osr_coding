def analyze_layer_transitions(all_features, all_labels):
    """Analyze how features change through the FC projection layers."""
    print("\n" + "=" * 70)
    print("Bonus: Layer Transition Analysis")
    print("=" * 70)

    fig, axes = plt.subplots(1, 3, figsize=(18, 5))

    # Track class separation metric through layers
    layer_keys = ['yamnet_128', 'fc1_128', 'fc2_64', 'final_32']
    layer_names = ['yamnet', 'FC1', 'FC2', 'Final']

    # Compute silhouette score for each layer
    sil_scores = []
    for key in layer_keys:
        data = all_features[key]
        sil = silhouette_score(data, all_labels, metric='euclidean',
                              sample_size=min(3000, len(data)))
        sil_scores.append(sil)

    axes[0].plot(range(len(layer_names)), sil_scores, 'o-', color='steelblue',
                 linewidth=2, markersize=8)
    axes[0].set_xticks(range(len(layer_names)))
    axes[0].set_xticklabels(layer_names)
    axes[0].set_ylabel('Silhouette Score')
    axes[0].set_title('Class Separability through Layers', fontsize=11, fontweight='bold')
    axes[0].grid(alpha=0.3)
    for i, v in enumerate(sil_scores):
        axes[0].text(i, v + 0.003, f'{v:.4f}', ha='center', fontsize=9)

    # Average inter-class distance through layers
    avg_dists = []
    for key in layer_keys:
        data = all_features[key]
        centroids = []
        for cls_id in range(NUM_CLASSES):
            mask = all_labels == cls_id
            if mask.sum() > 0:
                centroids.append(data[mask].mean(axis=0))
        centroids = np.array(centroids)
        dists = pairwise_distances(centroids, metric='euclidean')
        # Average off-diagonal distance
        avg_dist = dists[np.triu_indices(len(centroids), k=1)].mean()
        avg_dists.append(avg_dist)

    axes[1].plot(range(len(layer_names)), avg_dists, 'o-', color='coral',
                 linewidth=2, markersize=8)
    axes[1].set_xticks(range(len(layer_names)))
    axes[1].set_xticklabels(layer_names)
    axes[1].set_ylabel('Avg Inter-Class Euclidean Distance')
    axes[1].set_title('Inter-Class Distance through Layers', fontsize=11, fontweight='bold')
    axes[1].grid(alpha=0.3)
    for i, v in enumerate(avg_dists):
        axes[1].text(i, v * 1.01, f'{v:.3f}', ha='center', fontsize=9)

    # Within-class variance through layers
    within_vars = []
    for key in layer_keys:
        data = all_features[key]
        total_var = 0
        for cls_id in range(NUM_CLASSES):
            mask = all_labels == cls_id
            if mask.sum() > 1:
                total_var += data[mask].var(axis=0).mean()
        within_vars.append(total_var / NUM_CLASSES)

    axes[2].plot(range(len(layer_names)), within_vars, 'o-', color='green',
                 linewidth=2, markersize=8)
    axes[2].set_xticks(range(len(layer_names)))
    axes[2].set_xticklabels(layer_names)
    axes[2].set_ylabel('Avg Within-Class Variance')
    axes[2].set_title('Within-Class Variance through Layers', fontsize=11, fontweight='bold')
    axes[2].grid(alpha=0.3)
    for i, v in enumerate(within_vars):
        axes[2].text(i, v * 1.01, f'{v:.4f}', ha='center', fontsize=9)

    plt.suptitle('Feature Transformation Analysis Across Layers', fontsize=14, fontweight='bold')
    plt.tight_layout()
    plt.savefig(f'{OUTPUT_DIR}/12_layer_transitions.png', facecolor='white')
    plt.close()
    print(f"\n  [OK] Saved: {OUTPUT_DIR}/12_layer_transitions.png")

    print("\n  Summary of layer transformations:")
    print(f"  {'Layer':12s} {'Silhouette':>12s} {'Inter-Dist':>12s} {'Intra-Var':>12s}")
    print("  " + "-" * 50)
    for i, name in enumerate(layer_names):
        print(f"  {name:12s} {sil_scores[i]:12.4f} {avg_dists[i]:12.4f} {within_vars[i]:12.4f}")


