# Feature Collection (batch processing)
# ============================================================
def collect_features(model, dataset, device='cuda', max_samples_per_class=None,
                     batch_size=256, split_name='calib'):
    """
    Run all samples through model and collect features per class.
    Returns:
        features_dict: {class_id: {'yamnet_128': np.array, 'fc1_128': ..., ...}}
        all_features: {'yamnet_128': np.array, ...} (concatenated across all samples)
        all_labels: np.array of class indices
    """
    print(f"\n  Collecting features from '{split_name}' split (batch_size={batch_size})...")

    extractor = FeatureExtractor(model, device)

    class_data = defaultdict(lambda: {
        'yamnet_128': [], 'fc1_128': [], 'fc2_64': [], 'final_32': [],
        'known_outputs': [], 'unknown_outputs': [], 'weights1': [], 'weights2': []
    })
    class_counts = defaultdict(int)

    loader = torch.utils.data.DataLoader(
        dataset, batch_size=batch_size, shuffle=False,
        num_workers=8, pin_memory=True, drop_last=False
    )

    for batch_idx, item in enumerate(tqdm(loader, desc='  Extracting features')):
        waveforms = item['source_audio']
        targets = item['target'].squeeze(1)
        label_indices = targets.argmax(dim=1).tolist()

        # Check if we need to skip some classes
        skip_mask = []
        for idx in label_indices:
            if max_samples_per_class is not None and class_counts[idx] >= max_samples_per_class:
                skip_mask.append(True)
            else:
                skip_mask.append(False)

        if all(skip_mask):
            continue

        result = extractor.extract_batch(waveforms)

        for i, cls_id in enumerate(label_indices):
            if skip_mask[i]:
                continue
            class_counts[cls_id] += 1
            for key in ['yamnet_128', 'fc1_128', 'fc2_64', 'final_32',
                         'known_outputs', 'unknown_outputs', 'weights1', 'weights2']:
                class_data[cls_id][key].append(result[key][i].numpy())

    extractor.remove_hooks()

    # Concatenate per class
    for cls_id in class_data:
        for key in class_data[cls_id]:
            class_data[cls_id][key] = np.array(class_data[cls_id][key])

    # Build all_features and all_labels
    all_features = {}
    all_labels = []
    all_feature_keys = ['yamnet_128', 'fc1_128', 'fc2_64', 'final_32',
                        'known_outputs', 'unknown_outputs', 'weights1', 'weights2']
    for key in all_feature_keys:
        arrays = []
        labels_part = []
        for cls_id in range(NUM_CLASSES):
            if cls_id in class_data and len(class_data[cls_id][key]) > 0:
                arrays.append(class_data[cls_id][key])
                labels_part.extend([cls_id] * len(class_data[cls_id][key]))
        if arrays:
            all_features[key] = np.concatenate(arrays, axis=0)
        else:
            all_features[key] = np.array([])
        if key == 'final_32':
            all_labels = np.array(labels_part)

    total = len(all_labels)
    print(f"  Collected features for {total} samples:")
    for cls_id in range(NUM_CLASSES):
        cnt = class_counts.get(cls_id, 0)
        role = "Known" if cls_id < NUM_KNOWN else "Unknown"
        print(f"    Class {cls_id:2d} ({LABEL_MAP[cls_id]:20s}, {role}): {cnt}")

    return class_data, all_features, all_labels


