# Analysis 3: Feature Dimension Variance Analysis
# ============================================================
def analyze_dimension_variance(all_features, all_labels):
    """Analyze variance explained by each feature dimension."""
    print("\n" + "=" * 70)
    print("Analysis 3: Feature Dimension Variance Analysis")
    print("=" * 70)

    fig, axes = plt.subplots(1, 3, figsize=(18, 5))

    for ax_idx, (key, name) in enumerate([
        ('yamnet_128', 'yamnet 128-d'),
        ('fc2_64', 'FC2 64-d'),
        ('final_32', 'Final 32-d')
    ]):
        data = all_features[key]
        dim_vars = data.var(axis=0)
        dim_means = data.mean(axis=0)
        dim_abs_mean = np.abs(dim_means)

        total_var = dim_vars.sum()
        var_ratio = dim_vars / total_var * 100
        cum_var = np.cumsum(var_ratio)

        ax = axes[ax_idx]
        x = np.arange(len(dim_vars))

        ax2 = ax.twinx()
        ax.bar(x, var_ratio, color='steelblue', alpha=0.6, label='Variance %')
        ax2.plot(x, cum_var, 'r-o', markersize=3, linewidth=1.5, label='Cumulative %')
        ax2.axhline(y=90, color='green', linestyle='--', alpha=0.5, label='90% threshold')
        ax2.axhline(y=95, color='orange', linestyle='--', alpha=0.5, label='95% threshold')

        # Mark low-variance dimensions
        low_var_threshold = 0.01 * var_ratio.max()
        low_var_dims = np.where(var_ratio < low_var_threshold)[0]
        if len(low_var_dims) > 0:
            ax.bar(low_var_dims, var_ratio[low_var_dims], color='red', alpha=0.4, label=f'Low var ({len(low_var_dims)})')

        ax.set_title(f'{name}\nTotal Var: {total_var:.2f}', fontsize=11, fontweight='bold')
        ax.set_xlabel('Dimension')
        ax.set_ylabel('Variance %', color='steelblue')
        ax2.set_ylabel('Cumulative %', color='red')
        ax.legend(fontsize=7, loc='upper left')
        ax2.legend(fontsize=7, loc='center right')
        ax.grid(alpha=0.2)

        # Print top dimensions
        top_k = min(10, len(dim_vars))
        top_dims = np.argsort(dim_vars)[::-1][:top_k]
        print(f"\n  {name} - Top {top_k} dimensions by variance:")
        for rank, dim in enumerate(top_dims):
            print(f"    Dim {dim:3d}: var={dim_vars[dim]:.6f} ({var_ratio[dim]:.2f}%), "
                  f"cum={cum_var[dim]:.1f}%")

        dims_90 = np.searchsorted(cum_var, 90) + 1
        dims_95 = np.searchsorted(cum_var, 95) + 1
        print(f"  Dimensions for 90% variance: {dims_90}/{len(dim_vars)}")
        print(f"  Dimensions for 95% variance: {dims_95}/{len(dim_vars)}")

    plt.suptitle('Per-Dimension Variance Explained', fontsize=14, fontweight='bold')
    plt.tight_layout()
    plt.savefig(f'{OUTPUT_DIR}/03_dimension_variance.png', facecolor='white')
    plt.close()
    print(f"\n  [OK] Saved: {OUTPUT_DIR}/03_dimension_variance.png")


