# Feature Extraction Hook
# ============================================================
class FeatureExtractor:
    """Extract intermediate features from the FinalModel pipeline."""

    def __init__(self, model, device='cuda'):
        self.model = model
        self.device = device
        self.model.eval()

        self._yamnet_features = None
        self._fc1_features = None
        self._fc2_features = None
        self._final_features = None

        # Register forward hooks
        self._hooks = []
        self._hooks.append(self.model.feature_model.register_forward_hook(self._hook_yamnet))
        self._hooks.append(self.model.fc1.register_forward_hook(self._hook_fc1))
        self._hooks.append(self.model.fc2.register_forward_hook(self._hook_fc2))
        self._hooks.append(self.model.fc3.register_forward_hook(self._hook_fc3))

    def _hook_yamnet(self, module, input, output):
        self._yamnet_features = output.detach()

    def _hook_fc1(self, module, input, output):
        self._fc1_features = output.detach()

    def _hook_fc2(self, module, input, output):
        self._fc2_features = output.detach()

    def _hook_fc3(self, module, input, output):
        self._final_features = output.detach()

    def remove_hooks(self):
        for h in self._hooks:
            h.remove()

    @torch.no_grad()
    def extract_batch(self, waveforms):
        """
        Run a batch of waveforms through the model and collect all features.
        Returns dict with keys: 'yamnet_128', 'fc1_128', 'fc2_64', 'final_32',
        plus all model outputs.
        """
        self._yamnet_features = None
        self._fc1_features = None
        self._fc2_features = None
        self._final_features = None

        waveforms = waveforms.to(self.device)
        known_outputs, unknown_outputs, unknown_outputs_aug, weights1, weights2 = self.model(waveforms)

        result = {
            'yamnet_128': self._yamnet_features.cpu(),
            'fc1_128': self._fc1_features.cpu(),
            'fc2_64': self._fc2_features.cpu(),
            'final_32': self._final_features.cpu(),
            'known_outputs': known_outputs.cpu(),
            'unknown_outputs': unknown_outputs.cpu(),
            'weights1': weights1.cpu(),
            'weights2': weights2.cpu(),
        }
        return result


